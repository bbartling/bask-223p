"""Shareable coverage gap report and draft local extension stubs.

Lexical matches are never treated as covered. Statuses:

* covered: reserved for a reviewer-approved, declared term URI (not used for string matches)
* partial: one or more lexical candidates need a person to confirm
* needs_extension: no standard term was found; a draft local stub may be proposed

Draft stubs are review artifacts only: they are not published terms and they do not
assert equivalence with Brick, ASHRAE 223P or Project Haystack.
"""
from __future__ import annotations

import csv
import json
import re
from dataclasses import dataclass, field
from html import escape
from pathlib import Path
from typing import Any

PROPOSED_NS = "https://example.org/bask-223p/extensions#"
GAP_STATUSES = {
    "covered": "a reviewer-approved URI declared in a loaded vocabulary (not a semantic endorsement)",
    "partial": "a reviewer should confirm a lexical candidate",
    "needs_extension": "no standard term found; a draft local stub may be proposed",
}
GAP_COLUMNS = [
    "row", "category", "requirement", "description", "gap_status", "audit_status",
    "best_fit_vocabulary", "closest_term", "closest_uri", "score", "reason", "reviewer_notes",
]


@dataclass
class GapTerm:
    row: int
    category: str
    requirement: str
    description: str = ""
    audit_status: str = ""
    reason: str = ""
    reviewer_notes: str = ""
    approved_uri: str = ""
    approved_vocabulary: str = ""
    candidates: list[dict[str, Any]] = field(default_factory=list)
    hints: list[dict[str, Any]] = field(default_factory=list)


def gap_status(term: GapTerm) -> str:
    if term.approved_uri:
        return "covered"
    if term.candidates:
        return "partial"
    return "needs_extension"


def closest(term: GapTerm) -> dict[str, Any]:
    if term.approved_uri:
        return {
            "best_fit_vocabulary": term.approved_vocabulary,
            "closest_term": term.requirement,
            "closest_uri": term.approved_uri,
            "score": "",
        }
    pool = term.candidates or term.hints
    if pool:
        hit = max(pool, key=lambda c: (float(c.get("score") or 0), str(c.get("uri") or "")))
        return {
            "best_fit_vocabulary": hit.get("ontology") or hit.get("vocabulary") or "",
            "closest_term": hit.get("label") or "",
            "closest_uri": hit.get("uri") or "",
            "score": hit.get("score", ""),
        }
    return {"best_fit_vocabulary": "", "closest_term": "", "closest_uri": "", "score": ""}


def gap_row(term: GapTerm) -> dict[str, Any]:
    info = closest(term)
    status = gap_status(term)
    return {
        "row": term.row,
        "category": term.category,
        "requirement": term.requirement,
        "description": term.description,
        "gap_status": status,
        "audit_status": term.audit_status or status,
        "best_fit_vocabulary": info["best_fit_vocabulary"],
        "closest_term": info["closest_term"],
        "closest_uri": info["closest_uri"],
        "score": info["score"],
        "reason": term.reason,
        "reviewer_notes": term.reviewer_notes,
    }


def _slug(text: str) -> str:
    parts = re.findall(r"[A-Za-z0-9]+", text or "")
    if not parts:
        return "Term"
    return "".join(p[:1].upper() + p[1:] for p in parts)[:80]


def propose_stubs(terms: list[GapTerm], out: Path, *, base_iri: str = PROPOSED_NS) -> dict[str, Path]:
    needed = [t for t in terms if gap_status(t) == "needs_extension"]
    out.mkdir(parents=True, exist_ok=True)
    used: dict[str, int] = {}
    class_chunks: list[str] = []
    shape_chunks: list[str] = []
    for term in needed:
        slug = _slug(term.requirement)
        used[slug] = used.get(slug, 0) + 1
        if used[slug] > 1:
            slug = f"{slug}{used[slug]}"
        label = term.requirement.replace("\\", "\\\\").replace('"', '\\"')
        definition = (term.description or term.reason or "No standard term was found in the loaded catalogs.").replace("\\", "\\\\").replace('"', '\\"')
        class_chunks.append(
            f"ex:{slug} a owl:Class ;\n"
            f'  rdfs:label "{label}" ;\n'
            f'  skos:definition "{definition}" ;\n'
            f'  rdfs:comment "DRAFT for review only. Not a published term and not equivalent to a Brick, ASHRAE 223P or Haystack class." .\n'
        )
        shape_chunks.append(
            f"ex:{slug}Shape a sh:NodeShape ;\n"
            f"  sh:targetClass ex:{slug} ;\n"
            f'  sh:name "{label}" ;\n'
            f"  sh:property [ sh:path rdfs:label ; sh:minCount 1 ; sh:datatype xsd:string ] .\n"
        )
    header = (
        "# Draft extension stubs generated by bask-223p.\n"
        "# REVIEW ONLY. Do not merge into a standard ontology or a live site model until a person approves them.\n"
        f"@prefix ex: <{base_iri}> .\n"
        "@prefix owl: <http://www.w3.org/2002/07/owl#> .\n"
        "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .\n"
        "@prefix skos: <http://www.w3.org/2004/02/skos/core#> .\n"
        "@prefix sh: <http://www.w3.org/ns/shacl#> .\n"
        "@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .\n\n"
        f"<{base_iri.rstrip('#')}> a owl:Ontology ;\n"
        '  rdfs:label "Draft proposed extension terms" ;\n'
        '  rdfs:comment "Review artifacts only." .\n\n'
    )
    classes = out / "proposed-classes.ttl"
    shapes = out / "proposed-shapes.ttl"
    classes.write_text(header + ("\n".join(class_chunks) + ("\n" if class_chunks else "")), encoding="utf-8")
    shapes.write_text(header + ("\n".join(shape_chunks) + ("\n" if shape_chunks else "")), encoding="utf-8")
    return {"proposed_classes": classes, "proposed_shapes": shapes}


def write_gap_report(terms: list[GapTerm], out: Path, *, title: str = "Ontology coverage gap report") -> dict[str, Path]:
    out.mkdir(parents=True, exist_ok=True)
    records = [gap_row(t) for t in terms]
    counts = {k: 0 for k in GAP_STATUSES}
    for rec in records:
        counts[rec["gap_status"]] = counts.get(rec["gap_status"], 0) + 1
    payload = {
        "title": title,
        "gap_statuses": GAP_STATUSES,
        "gap_summary": counts,
        "terms": len(records),
        "note": "Lexical candidates are never treated as covered. Every candidate requires human review.",
        "rows": records,
    }
    paths = {
        "gap_json": out / "gap-report.json",
        "gap_csv": out / "gap-report.csv",
        "gap_md": out / "gap-report.md",
        "gap_html": out / "gap-report.html",
    }
    paths["gap_json"].write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    with paths["gap_csv"].open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=GAP_COLUMNS)
        w.writeheader()
        w.writerows(records)
    lines = [
        f"# {title}",
        "",
        payload["note"],
        "",
        "| Gap status | Count | Meaning |",
        "|---|---|---|",
    ]
    lines += [f"| {k} | {counts[k]} | {GAP_STATUSES[k]} |" for k in GAP_STATUSES]
    lines += ["", f"Total terms: {len(records)}", "", "## Terms", "",
              "| Requirement | Category | Gap status | Best fit | Closest term | URI |",
              "|---|---|---|---|---|---|"]
    for rec in records:
        lines.append(
            f"| {rec['requirement']} | {rec['category']} | {rec['gap_status']} | "
            f"{rec['best_fit_vocabulary']} | {rec['closest_term']} | {rec['closest_uri']} |"
        )
    paths["gap_md"].write_text("\n".join(lines) + "\n", encoding="utf-8")
    cells = "".join(
        "<tr>" + "".join(f"<td>{escape(str(rec[c]))}</td>" for c in GAP_COLUMNS) + "</tr>"
        for rec in records
    )
    head = "".join(f"<th>{escape(c.replace('_', ' '))}</th>" for c in GAP_COLUMNS)
    metrics = "".join(
        f"<div class='metric'><b>{counts[k]}</b>{escape(k)}</div>" for k in GAP_STATUSES
    )
    paths["gap_html"].write_text(
        "<!doctype html><html lang='en'><head><meta charset='utf-8'>"
        f"<title>{escape(title)}</title>"
        "<style>body{font:15px system-ui,sans-serif;max-width:1400px;margin:auto;padding:24px;color:#1c2b41}"
        "h1{color:#14365b}.metrics{display:flex;flex-wrap:wrap;gap:12px;margin:16px 0}"
        ".metric{background:#fff;border:1px solid #d5dce6;border-radius:10px;padding:12px 18px}"
        ".metric b{display:block;font-size:24px}.note{border-left:4px solid #d28c13;background:#fff6e6;padding:12px}"
        "table{border-collapse:collapse;width:100%}td,th{padding:8px;border-bottom:1px solid #e4e8ee;text-align:left}"
        "th{background:#ecf1f7}input{padding:8px;margin:12px 0;width:min(420px,90%)}</style></head><body>"
        f"<h1>{escape(title)}</h1><div class='note'>{escape(payload['note'])}</div>"
        f"<div class='metrics'>{metrics}</div>"
        "<label for='filter'>Filter</label><div><input id='filter' type='search'></div>"
        f"<table id='results'><thead><tr>{head}</tr></thead><tbody>{cells}</tbody></table>"
        "<script>document.getElementById('filter').addEventListener('input',function(){let q=this.value.toLowerCase();"
        "for(let row of document.querySelectorAll('#results tbody tr')){row.hidden=!row.textContent.toLowerCase().includes(q);}});</script>"
        "</body></html>",
        encoding="utf-8",
    )
    return paths
